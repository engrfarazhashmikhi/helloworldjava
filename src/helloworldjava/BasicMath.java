package helloworldjava;

public class BasicMath {
	public void generalMath() {
		double PI = Math.PI;
		System.out.format("Value of (PI): %f%n", (PI));
		System.out.format("Square Root Of PI: %f%n", (Math.sqrt(PI)));
		System.out.format("%s %f%n", "Addition of PI: ", (PI + PI));
		System.out.format("SIN if (PI): %f", Math.sin(PI));
	}
}
